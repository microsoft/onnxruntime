"""Create a deterministic Cargo .crate archive from an in-tree crate."""

import argparse
import gzip
import io
import re
import tarfile
from pathlib import Path


def _manifest_value(manifest: str, key: str) -> str:
    match = re.search(rf'(?m)^{re.escape(key)}\s*=\s*"([^"]+)"\s*$', manifest)
    if not match:
        raise ValueError(f"Cargo manifest does not define {key}.")
    return match.group(1)


def _normalized_manifest(original: str) -> str:
    normalized = original.replace('readme = "../README.md"', 'readme = "README.md"')
    normalized = re.sub(
        r'(?m)^onnxruntime-sys\s*=\s*\{\s*version\s*=\s*"([^"]+)",\s*path\s*=\s*"[^"]+"\s*\}\s*$',
        r'onnxruntime-sys = "\1"',
        normalized,
    )
    return (
        "# THIS FILE IS AUTOMATICALLY GENERATED BY THE ONNX RUNTIME RELEASE PACKAGER.\n"
        "# The original manifest is available as Cargo.toml.orig.\n\n" + normalized
    )


def _add_file(archive: tarfile.TarFile, name: str, data: bytes):
    info = tarfile.TarInfo(name)
    info.size = len(data)
    info.mode = 0o644
    info.mtime = 0
    info.uid = 0
    info.gid = 0
    info.uname = ""
    info.gname = ""
    archive.addfile(info, io.BytesIO(data))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--readme", type=Path, required=True)
    parser.add_argument("--release-notes", type=Path, required=True)
    parser.add_argument("--license", type=Path, nargs="*", default=[])
    parser.add_argument("--source", type=Path, nargs="*", default=[])
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    manifest_path = args.manifest.resolve()
    crate_dir = manifest_path.parent
    original = manifest_path.read_text(encoding="utf-8")
    crate_name = _manifest_value(original, "name")
    version = _manifest_value(original, "version")
    expected_name = f"{crate_name}-{version}.crate"
    if args.output.name != expected_name:
        raise ValueError(f"Output must be version-derived as {expected_name}, got {args.output.name}.")

    entries = {
        "Cargo.toml": _normalized_manifest(original).encode(),
        "Cargo.toml.orig": original.encode(),
        "README.md": args.readme.read_bytes(),
        "ORT_NATIVE_SDK.md": args.release_notes.read_bytes(),
    }
    for license_path in args.license:
        entries[license_path.name] = license_path.read_bytes()
    for source_path in args.source:
        source = source_path.resolve()
        try:
            relative = source.relative_to(crate_dir).as_posix()
        except ValueError as error:
            raise ValueError(f"Crate source is outside {crate_dir}: {source}") from error
        if relative in entries or relative in {"BUILD.bazel", ".gitignore"}:
            continue
        entries[relative] = source.read_bytes()

    root = f"{crate_name}-{version}"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with (
        args.output.open("wb") as raw,
        gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as compressed,
        tarfile.open(fileobj=compressed, mode="w") as archive,
    ):
        for relative, data in sorted(entries.items()):
            _add_file(archive, f"{root}/{relative}", data)


if __name__ == "__main__":
    main()

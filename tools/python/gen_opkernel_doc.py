import argparse
import hashlib
import io
import json
import os
import pathlib
from collections import defaultdict

import onnxruntime as ort
import onnxruntime.capi.onnxruntime_pybind11_state as rtpy


def format_version_range(v):
    if v[1] >= 2147483647:
        return str(v[0]) + "+"
    else:
        if v[0] == v[1]:
            return str(v[0])
        else:
            return "[" + str(v[0]) + ", " + str(v[1]) + "]"


def format_type_constraints(tc):
    tcstr = ""
    firsttcitem = True
    for tcitem in tc:
        if firsttcitem:
            firsttcitem = False
        else:
            tcstr += ", "
        tcstr += tcitem
    return tcstr


def format_param_strings(params):
    firstparam = True
    s = ""
    if params:
        for param in sorted(params):
            if firstparam:
                firstparam = False
            else:
                s += "<br><br>or<br><br>"
            s += param
    return s


def expand_providers(provider_filter: [str]):
    providers = set()
    if provider_filter:
        for provider in provider_filter:
            p = provider.lower()
            if not p.endswith("executionprovider"):
                p += "executionprovider"
            providers.add(p)

    return providers


def load_plugin_ep_kernel_defs(plugin_eps):
    """Register plugin EP libraries and return their kernel defs.

    Args:
        plugin_eps: list of "name:path" strings, e.g.
            ["CUDAExecutionProvider:/path/to/lib.so"]

    Returns:
        list of KernelDef objects from the plugin EPs.
    """
    if not plugin_eps:
        return []

    defs = []
    for spec in plugin_eps:
        ep_name, separator, lib_path = spec.partition(":")
        if not separator or not ep_name or not lib_path:
            raise ValueError(f"Invalid --plugin-ep spec '{spec}' (expected NAME:PATH)")
        if not pathlib.Path(lib_path).is_file():
            raise FileNotFoundError(f"Plugin EP library does not exist: {lib_path}")

        ort.register_execution_provider_library(ep_name, lib_path)
        kernels = rtpy.get_registered_ep_kernel_defs(ep_name)
        if not kernels:
            raise RuntimeError(f"Plugin EP '{ep_name}' returned no registered kernels")
        if any(kernel.provider != ep_name for kernel in kernels):
            raise RuntimeError(f"Plugin EP '{ep_name}' returned kernels for a different execution provider")
        defs.extend(kernels)

    return defs


def main(output_path: pathlib.Path, provider_filter: [str], plugin_eps=None, metadata_path=None):
    providers = expand_providers(provider_filter)
    if metadata_path is not None and metadata_path.resolve() == pathlib.Path(output_path).resolve():
        raise ValueError("The documentation and metadata output paths must be different")

    # Complete all queries and rendering before replacing an existing document.
    with io.StringIO() as fout:
        fout.write("## Supported Operators and Data Types\n")
        fout.write(
            "*This file is automatically generated from the registered kernels by "
            "[this script](https://github.com/microsoft/onnxruntime/blob/main/tools/python/gen_opkernel_doc.py).\n"
            "Do not modify directly.*\n\n"
        )
        fout.write(
            "### Version Notation\n\n"
            "The **OpSet Version** column uses the following notation:\n\n"
            "- `N` — registered only for opset N (e.g., `13`).\n"
            "- `[N, M]` — registered for opsets N through M inclusive (e.g., `[6, 12]`).\n"
            "- `N+` — registered for opset N and all later opsets until superseded by a newer"
            " kernel registration (e.g., `16+`).\n\n"
        )
        opdef = rtpy.get_all_operator_schema()
        paramdict = {}
        for schema in opdef:
            inputs = schema.inputs
            domain = schema.domain
            if not domain:
                domain = "ai.onnx"
            fullname = domain + "." + schema.name
            paramstr = ""
            firstinput = True
            if inputs:
                for inp in inputs:
                    if firstinput:
                        firstinput = False
                    else:
                        paramstr += "<br> "
                    paramstr += f"*in* {inp.name}:**{inp.typeStr}**"

            outputs = schema.outputs
            if outputs:
                for outp in outputs:
                    if firstinput:
                        firstinput = False
                    else:
                        paramstr += "<br> "
                    paramstr += f"*out* {outp.name}:**{outp.typeStr}**"

            paramstr += ""
            paramset = paramdict.get(fullname)
            if paramset is None:
                paramdict[fullname] = set()

            paramdict[fullname].add(paramstr)

        index = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))
        for op in rtpy.get_all_opkernel_def():
            domain = op.domain
            if not domain:
                domain = "ai.onnx"
            index[op.provider][domain][op.op_name].append(op)

        # Include kernel defs from plugin EPs
        for op in load_plugin_ep_kernel_defs(plugin_eps):
            domain = op.domain
            if not domain:
                domain = "ai.onnx"
            index[op.provider][domain][op.op_name].append(op)

        # TOC
        fout.write("## Execution Providers\n\n")
        for provider in sorted(index.keys()):
            if providers and provider.lower() not in providers:
                continue
            fout.write(f"- [{provider}](#{provider.lower()})\n")
        fout.write("\n---------------")

        for provider, domainmap in sorted(index.items()):
            if providers and provider.lower() not in providers:
                continue

            fout.write(f'\n\n<a name="{provider.lower()}"/>\n\n')
            fout.write(f"## Operators implemented by {provider}\n\n")
            fout.write("| Op Name | Parameters | OpSet Version | Types Supported |\n")
            fout.write("|---------|------------|---------------|-----------------|\n")
            for domain, namemap in sorted(domainmap.items()):
                fout.write("|**Operator Domain:** *" + domain + "*||||\n")
                for name, ops in sorted(namemap.items()):
                    version_type_index = defaultdict(lambda: defaultdict(set))
                    for op in ops:
                        for tname, tclist in op.type_constraints.items():
                            for c in tclist:
                                version_type_index[op.version_range][tname].add(c)

                    namefirsttime = True
                    for version_range, typemap in sorted(version_type_index.items(), key=lambda x: x[0], reverse=True):
                        if namefirsttime:
                            params = paramdict.get(domain + "." + name, None)
                            fout.write("|" + name + "|" + format_param_strings(params) + "|")
                            namefirsttime = False
                        else:
                            fout.write("|||")
                        fout.write(format_version_range(version_range) + "|")
                        for i, (tname, tcset) in enumerate(sorted(typemap.items())):
                            tnameindex = i + 1
                            tclist = []
                            for tc in sorted(tcset):
                                tclist.append(tc)
                            fout.write("**" + tname + "** = " + format_type_constraints(tclist))
                            if tnameindex < len(typemap):
                                fout.write("<br/> ")
                        fout.write("|\n")

                fout.write("| |\n| |\n")

        content = fout.getvalue()

    metadata = None
    if metadata_path is not None:
        plugins = []
        if plugin_eps:
            devices = {device.ep_name: device for device in ort.get_ep_devices()}
            for spec in plugin_eps:
                ep_name, lib_path = spec.split(":", 1)
                library = pathlib.Path(lib_path)
                plugins.append(
                    {
                        "provider": ep_name,
                        "version": devices[ep_name].ep_metadata.get("version"),
                        "library": str(library.resolve()),
                        "sha256": hashlib.sha256(library.read_bytes()).hexdigest(),
                    }
                )

        metadata = {
            "onnxruntime_version": ort.__version__,
            "session_options": "default",
            "environment": {
                name: os.environ.get(name)
                for name in ("ORT_WEBGPU_EP_ALLOW_SOFTWARE_ADAPTER", "ALLOW_RELEASED_ONNX_OPSET_ONLY")
            },
            "plugins": plugins,
            "providers": {
                provider: {
                    "registrations": sum(len(ops) for namemap in domainmap.values() for ops in namemap.values()),
                    "operators": sum(len(namemap) for namemap in domainmap.values()),
                }
                for provider, domainmap in sorted(index.items())
                if not providers or provider.lower() in providers
            },
            "generator_sha256": hashlib.sha256(pathlib.Path(__file__).read_bytes()).hexdigest(),
            "document_sha256": hashlib.sha256(content.encode("utf-8")).hexdigest(),
        }

    with open(output_path, "w", newline="", encoding="utf-8") as fout:
        fout.write(content)
    if metadata is not None:
        with open(metadata_path, "w", newline="", encoding="utf-8") as fout:
            json.dump(metadata, fout, indent=2, sort_keys=True)
            fout.write("\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="ONNX Runtime Operator Kernel Documentation Generator")
    parser.add_argument(
        "--providers",
        nargs="+",
        help="Filter to specified execution providers. Case-insensitive. "
        "Matches provider names from <ORT>/include/onnxruntime/core/graph/constants.h'. "
        "'ExecutionProvider' is automatically appended as needed. "
        "e.g. `--providers cpu cuda` will match CPUExecutionProvider and CUDAExecutionProvider.",
    )
    parser.add_argument(
        "--plugin-ep",
        nargs="+",
        dest="plugin_eps",
        help="Register plugin EP libraries and include their kernels. "
        "Each entry is NAME:PATH, e.g. "
        "'CUDAExecutionProvider:/path/to/libonnxruntime_providers_cuda.so'. "
        "A registration or query failure, or an empty plugin registry, is an error.",
    )
    parser.add_argument(
        "--metadata_path",
        type=pathlib.Path,
        help="Optional JSON output recording runtime/plugin versions, registration counts, options, and hashes.",
    )
    parser.add_argument(
        "--output_path",
        help="output markdown file path",
        type=pathlib.Path,
        required=True,
        default=os.path.join(os.path.dirname(os.path.realpath(__file__)), "OperatorKernels.md"),
    )
    args = parser.parse_args()

    main(args.output_path, args.providers, args.plugin_eps, args.metadata_path)

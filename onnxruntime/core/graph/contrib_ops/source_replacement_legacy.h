// Exact-key union only. Optional training registration must not become an
// unclassified new schema; absent schemas do not imply build/kernel support.
inline gsl::span<const OpKey> LegacySourcePolicyKeys() {
  static const InlinedVector<OpKey> keys = [] {
    const auto inference = LegacyInferenceSourcePolicyKeys();
    const auto training = LegacyTrainingSourcePolicyKeys();
    InlinedVector<OpKey> combined(inference.begin(), inference.end());
    combined.insert(combined.end(), training.begin(), training.end());
    std::sort(combined.begin(), combined.end(), [](const auto& a, const auto& b) {
      return std::tie(a.domain, a.name, a.since_version) < std::tie(b.domain, b.name, b.since_version);
    });
    combined.erase(std::unique(combined.begin(), combined.end()), combined.end());
    return combined;
  }();
  return keys;
}
